"""Generate a CMake toolchain file for a gcc-env environment."""

from __future__ import annotations

from pathlib import Path

from .compiler import runtime_flags
from .envs import Environment


def _cmake_path(path: Path | str) -> str:
    return str(path).replace("\\", "/").replace('"', '\\"')


def render_toolchain(env: Environment, *, runtime: str | None = None) -> str:
    selected = runtime or env.runtime
    flags = runtime_flags(env.config.platform, selected)
    flag_text = " ".join(flags)
    root = _cmake_path(env.root)
    prefix = _cmake_path(env.conda_prefix)
    cc = _cmake_path(env.cc)
    cxx = _cmake_path(env.cxx)
    install_rpath = ""
    if selected == "bundle":
        install_rpath = "@loader_path/../lib" if env.config.platform.is_macos else "$ORIGIN/../lib"
    lines = [
        f"# Generated by gcc-env for environment {env.name}.",
        f"# GCC {env.gcc_version} ({env.gcc_target}); runtime policy: {selected}.",
        "# Use with: cmake -DCMAKE_TOOLCHAIN_FILE=<this file> ...",
        "",
        f'set(CMAKE_C_COMPILER "{cc}")',
        f'set(CMAKE_CXX_COMPILER "{cxx}")',
        "",
        'set(CMAKE_C_FLAGS_INIT "")',
        'set(CMAKE_CXX_FLAGS_INIT "")',
        f'set(CMAKE_EXE_LINKER_FLAGS_INIT "{flag_text}")',
        f'set(CMAKE_SHARED_LINKER_FLAGS_INIT "{flag_text}")',
        f'set(CMAKE_MODULE_LINKER_FLAGS_INIT "{flag_text}")',
        "",
        "set(CMAKE_BUILD_RPATH_USE_ORIGIN TRUE)",
    ]
    if install_rpath:
        lines.append(f'set(CMAKE_INSTALL_RPATH "{install_rpath}")')
        lines.append("set(CMAKE_INSTALL_RPATH_USE_LINK_PATH FALSE)")
    lines.extend(
        [
            "",
            f'list(PREPEND CMAKE_PREFIX_PATH "{prefix}")',
            f'list(PREPEND CMAKE_INCLUDE_PATH "{prefix}/include")',
            f'list(PREPEND CMAKE_LIBRARY_PATH "{prefix}/lib")',
            f'set(GE_ENV "{env.name}")',
            f'set(GE_ENV_ROOT "{root}")',
            "",
        ]
    )
    if env.sysroot:
        sysroot = _cmake_path(env.sysroot)
        lines.insert(
            lines.index(f'set(GE_ENV_ROOT "{root}")') + 1,
            f'set(GE_SYSROOT "{sysroot}")',
        )
    return "\n".join(lines)


def write_toolchain(
    env: Environment,
    destination: Path | None = None,
    *,
    runtime: str | None = None,
) -> Path:
    destination = destination or env.root / "ge-toolchain.cmake"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render_toolchain(env, runtime=runtime), encoding="utf-8")
    return destination
